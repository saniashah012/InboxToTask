// Deterministic staging: the canonical pipeline remains here, not a second fork.
import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const target = new URL('supabase/functions/_shared/extraction/', root);
for (const subdir of ['pipeline/', 'prompts/']) {
  await mkdir(new URL(subdir, target), { recursive: true });
}
for (const path of ['pipeline/core.mjs', 'pipeline/gemini.mjs', 'pipeline/gmail-retrieval.mjs', 'pipeline/task-context.mjs', 'pipeline/gmail-processor.mjs',
  'pipeline/provider-schema.mjs', 'pipeline/private-topics.mjs', 'prompts/extraction.schema.mjs']) {
  await copyFile(new URL(path, root), new URL(path, target));
}
const systemPrompt = await readFile(new URL('prompts/extraction.system.txt', root), 'utf8');
const settings = JSON.parse(await readFile(new URL('prompts/model-settings.json', root), 'utf8'));
const fixture = JSON.parse(await readFile(new URL('../tests/fixtures/cp2-inbox.json', root), 'utf8'));
await writeFile(new URL('assets.mjs', target),
  `// Generated by npm run supabase:prepare. No environment files are read.\n`
  + `export const systemPrompt = ${JSON.stringify(systemPrompt)};\n`
  + `export const settings = ${JSON.stringify(settings)};\n`
  + `export const fixture = ${JSON.stringify(fixture)};\n`, 'utf8');
console.log('Prepared canonical pipeline, prompt, settings, and fictional cases for Edge Functions.');
